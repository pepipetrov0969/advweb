export function allServices(): Array<Service & { category: ServiceCategory }> {
  return serviceCategories.flatMap((category) =>
    category.services.map((service) => ({ ...service, category })),
  );
}

export function getService(slug: string) {
  return allServices().find((s) => s.slug === slug);
}

export function featuredServices() {
  const all = allServices();
  return featuredServiceSlugs
    .map((slug) => all.find((s) => s.slug === slug))
    .filter((s): s is NonNullable<typeof s> => Boolean(s));
}

// Темите в падащото меню на формата за запазване на час.
export function bookingTopics() {
  return [...serviceCategories.map((c) => c.title), "Друго / не съм сигурен"];
}
